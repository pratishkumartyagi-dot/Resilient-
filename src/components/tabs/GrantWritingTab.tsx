const buildPrompt = (ctx: PipelineContext, funder: string): string =>
  `You are an expert grant-writing assistant. Write a complete, funder-tailored grant proposal for ${funder}.\n\n` +
  `Include sections A–K:\n` +
  `A. PROJECT OVERVIEW\nB. ABSTRACT / SUMMARY\nC. SPECIFIC AIMS\nD. INNOVATION & SIGNIFICANCE\n` +
  `E. APPROACH / METHODOLOGY\nF. EXPECTED OUTCOMES & DELIVERABLES\nG. INVESTIGATOR TEAM & TRACK RECORD\n` +
  `H. BUDGET NARRATIVE (SUMMARY) with a budget table\nI. HUMAN SUBJECTS / ETHICS\nJ. TIMELINE\nK. LETTERS OF SUPPORT\n\n` +
  `The budget table must be internally consistent: every row total must equal the sum of its yearly values, and the TOTAL row must equal the sum of the category totals. State the same grand total in the PROJECT OVERVIEW.\n\n` +
  `Base the proposal on this pipeline data:\n` +
  `Title: ${ctx.title || "(not provided)"}\n` +
  `Aim: ${ctx.aim || "(not provided)"}\n` +
  `Primary objective: ${ctx.primaryObjective || "(not provided)"}\n` +
  `Secondary objectives: ${ctx.secondaryObjectives.join("; ") || "(not provided)"}\n` +
  `Study site: ${ctx.studySite || "(not provided)"}\n` +
  `Setting: ${ctx.setting || "(not provided)"}\n` +
  `Population: ${ctx.population || "(not provided)"}\n` +
  `Inclusion criteria: ${ctx.inclusionCriteria || "(not provided)"}\n` +
  `Exclusion criteria: ${ctx.exclusionCriteria || "(not provided)"}\n` +
  `Hypothesis: ${ctx.hypothesis || "(not provided)"}\n` +
  `Outcomes: ${ctx.outcomes.join("; ") || "(not provided)"}\n\n` +
  `Return plain text with the section headings above. Do not invent numeric results.`;

interface ImportedData {
  title: string;
  aim: string;
  objective: string;
  site: string;
}

export default function GrantWritingTab() {
  const { state } = useApp();
  const [selectedFunder, setSelectedFunder] = useState(FUNDERS[0]);
  const [proposal, setProposal] = useState("");
  const [isGenerating, setIsGenerating] = useState(false);
  const [showExportMenu, setShowExportMenu] = useState(false);
  const [imported, setImported] = useState<ImportedData | null>(null);
  const [importNotice, setImportNotice] = useState("");

  const buildPipelineContext = (): PipelineContext => ({
    title: imported?.title || state.userTitleInput || "",
    aim: imported?.aim || state.aimObjectives.aim || "",
    primaryObjective: imported?.objective || state.aimObjectives.primaryObjective || "",
    secondaryObjectives: state.aimObjectives.secondaryObjectives || [],
    studySite: imported?.site || state.methodology.studySite || "",
    setting: state.methodology.setting || "",
    population: state.methodology.population || "",
    inclusionCriteria: state.methodology.inclusionCriteria || "",
    exclusionCriteria: state.methodology.exclusionCriteria || "",
    hypothesis: state.methodology.hypothesis || "",
    outcomes: state.methodology.outcomes || [],
  });

  const handleGenerate = async () => {
    setIsGenerating(true);
    setProposal("");
    const ctx = buildPipelineContext();
    const prompt = buildPrompt(ctx, selectedFunder);

    let text = "";
    try {
      if (state.geminiApiKey) text = await callGemini(state.geminiApiKey, prompt);
      else if (state.groqApiKey) text = await callGroq(state.groqApiKey, prompt);
      else text = await callDeepSeek(prompt);
    } catch {
      text = "";
    }
    if (!text.trim()) text = generateTemplateProposal(ctx, selectedFunder);

    setProposal(text);
    setIsGenerating(false);
  };

  const handleAutoImport = () => {
    const data: ImportedData = {
      title: state.userTitleInput || "",
      aim: state.aimObjectives.aim || "",
      objective: state.aimObjectives.primaryObjective || "",
      site: state.methodology.studySite || "",
    };
    setImported(data);
    setImportNotice("Pipeline data imported — generated proposals will use these values.");
    setTimeout(() => setImportNotice(""), 5000);
  };

  return (
    <div className="space-y-6">
      <div className="bg-[#0d1b3e] border border-blue-900/50 rounded-lg p-6 shadow">
        <div className="flex items-center justify-between mb-4">
          <div>
            <h2 className="text-xl font-bold text-white">Grant Writing</h2>
            <p className="text-sm text-blue-300">
              Auto-generated grant proposal with sections imported directly from your research pipeline.
            </p>
          </div>
          <button
            onClick={handleAutoImport}
            className="text-sm bg-blue-900/50 text-blue-200 px-4 py-2 rounded-lg hover:bg-blue-900/70 flex items-center gap-1"
          >
            <Info size={14} />
            Auto-Import Pipeline Data
          </button>
        </div>

        {importNotice && (
          <div className="mb-4 flex items-center gap-2 text-sm text-green-300 bg-green-950/40 border border-green-800/50 rounded-lg px-3 py-2">
            <CheckCircle size={14} />
            {importNotice}
          </div>
        )}

        {imported && (
          <div className="mb-6 bg-blue-950/60 border border-blue-900 rounded-lg p-4 text-xs text-blue-200 space-y-1">
            <p className="text-sm font-semibold text-white mb-1">Imported from research pipeline</p>
            <p><span className="text-blue-400">Title:</span> {imported.title || "(not set in Step 7)"}</p>
            <p><span className="text-blue-400">Aim:</span> {imported.aim || "(not set in Step 8)"}</p>
            <p><span className="text-blue-400">Primary objective:</span> {imported.objective || "(not set in Step 8)"}</p>
            <p><span className="text-blue-400">Study site:</span> {imported.site || "(not set in Step 9)"}</p>
          </div>
        )}

        <div className="flex flex-wrap items-center gap-4 mb-6">
          <div className="relative">
            <select
              value={selectedFunder}
              onChange={(e) => setSelectedFunder(e.target.value)}
              className="appearance-none bg-blue-950 border border-blue-800 text-white rounded-lg pl-4 pr-10 py-2.5 text-sm"
            >
              {FUNDERS.map((f) => (
                <option key={f} value={f}>{f}</option>
              ))}
            </select>
            <ChevronRight size={12} className="absolute right-3 top-1/2 -translate-y-1/2 text-blue-400 rotate-[-90deg] pointer-events-none" />
          </div>

          <button
            onClick={handleGenerate}
            disabled={isGenerating}
            className="bg-yellow-500 hover:bg-yellow-600 text-[#0a1a3a] font-bold px-6 py-2.5 rounded-lg disabled:opacity-50 flex items-center gap-2"
          >
            <Sparkles size={16} />
            {isGenerating ? "Generating Proposal..." : "Generate Grant Proposal"}
          </button>

          {proposal && (
            <div className="relative ml-auto">
              <button
                onClick={() => setShowExportMenu(!showExportMenu)}
                className="bg-green-900/50 text-green-300 px-4 py-2 rounded-lg hover:bg-green-900/70 flex items-center gap-2 text-sm"
              >
                <Download size={14} />
                Export
              </button>
              {showExportMenu && (
                <div className="absolute right-0 top-full mt-1 bg-[#0a1530] border border-blue-800 rounded-lg shadow-lg overflow-hidden z-10 w-48">
                  <button
                    onClick={() => { void downloadMarkdownAsWord(proposal, "grant-proposal.docx"); setShowExportMenu(false); }}
                    className="w-full text-left px-4 py-2 text-sm text-white hover:bg-blue-900/50 flex items-center gap-2"
                  >
                    <FileText size={14} /> Export as Word
                  </button>
                  <button
                    onClick={() => { downloadMarkdownAsPDF(proposal, "grant-proposal.pdf"); setShowExportMenu(false); }}
                    className="w-full text-left px-4 py-2 text-sm text-white hover:bg-blue-900/50 flex items-center gap-2"
                  >
                    <Download size={14} /> Export as PDF
                  </button>
                </div>
              )}
            </div>
          )}
        </div>

        {isGenerating && (
          <div className="flex items-center justify-center py-16">
            <div className="text-center">
              <div className="w-10 h-10 border-4 border-yellow-400 border-t-transparent rounded-full animate-spin mx-auto mb-4" />
              <p className="text-blue-200 text-sm">Composing grant proposal sections...</p>
              <p className="text-blue-400 text-xs mt-1">Tailoring to {selectedFunder} format</p>
            </div>
          </div>
        )}

        {!isGenerating && !proposal && (
          <div className="text-center py-16 text-blue-400">
            <FlaskConical size={40} className="mx-auto mb-3 opacity-50" />
            <p className="text-sm">Select a funder and generate a tailored grant proposal draft pre-populated from your pipeline.</p>
          </div>
        )}

        {proposal && !isGenerating && (
          <div>
            <div className="bg-blue-950/50 border border-blue-900 rounded-lg p-5 max-h-[600px] overflow-y-auto">
              <pre className="text-sm text-blue-100 whitespace-pre-wrap font-mono leading-relaxed">{proposal}</pre>
            </div>
          </div>
        )}
      </div>
    </div>
  );
}

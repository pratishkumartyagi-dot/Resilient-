interface PipelineContext {
  title: string;
  aim: string;
  primaryObjective: string;
  secondaryObjectives: string[];
  studySite: string;
  setting: string;
  population: string;
  inclusionCriteria: string;
  exclusionCriteria: string;
  hypothesis: string;
  outcomes: string[];
}

const usd = (n: number) => `$${n.toLocaleString("en-US")}`;

const buildBudgetTable = (): { table: string; grandTotal: number } => {
  const rows = [
    { category: "Personnel", y1: 210000, y2: 220000, y3: 230000 },
    { category: "Equipment (IGRA)", y1: 95000, y2: 95000, y3: 95000 },
    { category: "Digital intervention", y1: 35000, y2: 25000, y3: 15000 },
    { category: "Training/dissem.", y1: 40000, y2: 50000, y3: 55000 },
    { category: "Overhead (30%)", y1: 66000, y2: 66000, y3: 66000 },
  ];
  const rowTotal = (r: (typeof rows)[number]) => r.y1 + r.y2 + r.y3;
  const y1 = rows.reduce((s, r) => s + r.y1, 0);
  const y2 = rows.reduce((s, r) => s + r.y2, 0);
  const y3 = rows.reduce((s, r) => s + r.y3, 0);
  const grandTotal = rows.reduce((s, r) => s + rowTotal(r), 0);

  const pad = (v: string, w: number) => v.padStart(w);
  const col = (v: string, w: number) => v.padEnd(w);

  const lines = [
    `| ${col("Category", 20)} | ${pad("Year 1", 9)} | ${pad("Year 2", 9)} | ${pad("Year 3", 9)} | ${pad("Total", 11)} |`,
    `|${"-".repeat(22)}|${"-".repeat(11)}|${"-".repeat(11)}|${"-".repeat(11)}|${"-".repeat(13)}|`,
    ...rows.map(
      (r) => `| ${col(r.category, 20)} | ${pad(usd(r.y1), 9)} | ${pad(usd(r.y2), 9)} | ${pad(usd(r.y3), 9)} | ${pad(usd(rowTotal(r)), 11)} |`
    ),
    `|${"-".repeat(22)}|${"-".repeat(11)}|${"-".repeat(11)}|${"-".repeat(11)}|${"-".repeat(13)}|`,
    `| ${col("TOTAL", 20)} | ${pad(usd(y1), 9)} | ${pad(usd(y2), 9)} | ${pad(usd(y3), 9)} | ${pad(usd(grandTotal), 11)} |`,
  ];

  return { table: lines.join("\n"), grandTotal };
};

